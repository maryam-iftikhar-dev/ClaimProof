app.post('/api/decision', requireAuth, (req, res) => {

    const state = req.session.latest;
    const { decision, note = '' } = req.body || {};

    const allowed = [
        'confirmed_edited',
        'genuine',
        'unsure'
    ];

    if (!state) {
        return res.status(400).json({
            error: 'Analyse an image before saving a decision.'
        });
    }

    if (!allowed.includes(decision)) {
        return res.status(400).json({
            error: 'Select a valid analyst decision.'
        });
    }

    fs.mkdirSync(feedbackDir, { recursive: true });

    const id = crypto.createHash('sha1')
        .update(state.photoBuffer)
        .digest('hex')
        .slice(0, 10);

    const csv = path.join(feedbackDir, 'analyst_decisions.csv');

    const headers =
        'time,photo_id,model_score,model_flagged,analyst_decision,note,regions\n';

    const row = [
        new Date().toISOString(),
        id,
        state.score,
        state.flagged ? 1 : 0,
        decision,
        note.replace(/[\r\n,]/g, ' '),
        JSON.stringify(state.regions).replace(/"/g, '""')
    ].map(v => `"${String(v).replace(/"/g, '""')}"`).join(',') + '\n';

    if (!fs.existsSync(csv)) {
        fs.writeFileSync(csv, headers);
    }

    fs.appendFileSync(csv, row);

    const folder = path.join(feedbackDir, decision);

    fs.mkdirSync(folder, { recursive: true });

    fs.writeFileSync(
        path.join(folder, `${id}.jpg`),
        Buffer.from(state.photoBuffer, 'base64')
    );

    const agrees = decision !== 'unsure' &&
        ((decision === 'confirmed_edited') === state.flagged);

    res.json({
        message: `Decision saved for photo ${id}. ${
            decision === 'unsure'
                ? 'The case is marked for further review.'
                : agrees
                    ? 'The analyst agrees with the detector.'
                    : 'The analyst decision differs from the detector.'
        }`
    });
});

