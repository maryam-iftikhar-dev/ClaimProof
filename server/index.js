// IMAGE ANALYSIS + GEMINI EXPLANATION
// --------------------------------------------------

app.post('/api/analyze', requireAuth, upload.single('image'), async (req, res) => {

    if (!req.file) {
        return res.status(400).json({
            error: 'Choose an image first.'
        });
    }

    try {

        const FormData = require('form-data');
        const form = new FormData();

        form.append('file', req.file.buffer, {
            filename: req.file.originalname,
            contentType: req.file.mimetype
        });

        // STEP 1: Run SegFormer-B2 image analysis.
        const response = await axios.post(
            `${INFERENCE_URL}/analyze`,
            form,
            {
                headers: form.getHeaders(),
                maxBodyLength: 20 * 1024 * 1024,
                timeout: 180000
            }
        );

        const result = { ...response.data };

        // STEP 2: Ask Gemini to explain ONLY the model findings.
        const aiExplanation = await generateGeminiExplanation(result);

        result.reason = aiExplanation.text;
        result.explanation_provider = aiExplanation.provider;

        // STEP 3: Preserve the result for analyst feedback.
        req.session.latest = {
            ...result,
            originalName: req.file.originalname,
            photoBuffer: result.processed_image.split(',')[1]
        };

        // STEP 4: Return results to the frontend.
        res.json(result);

    } catch (err) {

        const status = err.response?.status || 503;

        res.status(status).json({
            error: err.response?.data?.detail ||
                'The model service could not analyse the image. Check that it is running.'
        });
    }
});

