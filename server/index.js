
const express = require('express');
const session = require('express-session');
const helmet = require('helmet');
const rateLimit = require('express-rate-limit');
const multer = require('multer');
const axios = require('axios');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const app = express();

const ROOT = path.resolve(__dirname, '..');

// Load private environment variables from the project root
require('dotenv').config({ path: path.join(ROOT, '.env') });

const PORT = process.env.PORT || 3000;
const INFERENCE_URL = process.env.INFERENCE_URL || 'http://127.0.0.1:8001';

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const GEMINI_MODEL = process.env.GEMINI_MODEL || 'gemini-3.8-flash';

const users = JSON.parse(
    fs.readFileSync(path.join(ROOT, 'config/demo-users.json'), 'utf8')
);

const feedbackDir = path.join(ROOT, 'analyst_feedback');

const upload = multer({
    storage: multer.memoryStorage(),
    limits: { fileSize: 15 * 1024 * 1024 },
    fileFilter: (req, file, cb) => {
        const allowed = [
            'image/jpeg',
            'image/png',
            'image/webp',
            'image/bmp'
        ];

        cb(
            allowed.includes(file.mimetype)
                ? null
                : new Error('Only JPG, PNG, WEBP, and BMP images are supported.'),
            allowed.includes(file.mimetype)
        );
    }
});

app.use(helmet({ contentSecurityPolicy: false }));
app.use(express.json({ limit: '1mb' }));

app.use(session({
    secret: process.env.SESSION_SECRET ||
        'change-this-demo-session-secret-before-deployment',
    resave: false,
    saveUninitialized: false,
    cookie: {
        httpOnly: true,
        sameSite: 'lax',
        secure: false,
        maxAge: 8 * 60 * 60 * 1000
    }
}));

app.use(express.static(path.join(ROOT, 'public')));

// Authentication
const loginLimiter = rateLimit({
    windowMs: 15 * 60 * 1000,
    limit: 30,
    standardHeaders: true,
    legacyHeaders: false
});

function requireAuth(req, res, next) {
    if (!req.session.user) {
        return res.status(401).json({
            error: 'Please log in to continue.'
        });
    }
    next();
}

function safeEqual(a, b) {
    const aa = Buffer.from(String(a));
    const bb = Buffer.from(String(b));

    return aa.length === bb.length &&
        crypto.timingSafeEqual(aa, bb);
}

